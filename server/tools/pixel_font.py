"""Turn a pixel TTF into an LVGL 9 bitmap font (C source), scaled by whole pixels so it stays crisp.

    uv run python tools/pixel_font.py FONT.ttf --grid 8 --scale 2 --name font_pixel_16 --out font.c [--preview p.png]

The font is rasterised at its design grid (8 px for Press Start 2P) without antialiasing and
every pixel becomes scale x scale. Covers ASCII, Latin-1 and a few typographic signs (… ¿ ¡ « »
€ and curly quotes): what Bixo's Spanish screen texts use. Other characters fall back to the
theme font at runtime (lv_font_t.fallback).
"""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

CHARS = [chr(c) for c in range(0x20, 0x7F)] + [chr(c) for c in range(0xA0, 0x100)] + \
        ["‘", "’", "“", "”", "…", "€"]


def rasterise(font: ImageFont.FreeTypeFont, ch: str, grid: int) -> tuple[list[list[int]], int, int, int]:
    """Glyph rows (top to bottom), ofs_x and ofs_y (box bottom above the baseline), advance."""
    size = grid * 4
    img = Image.new("1", (size, size), 0)
    draw = ImageDraw.Draw(img)
    draw.fontmode = "1"
    origin_x, baseline = grid, grid * 2
    draw.text((origin_x, baseline), ch, font=font, fill=1, anchor="ls")
    advance = round(font.getlength(ch))
    bbox = img.getbbox()
    if bbox is None:
        return [], 0, 0, advance
    left, top, right, bottom = bbox
    rows = [[img.getpixel((x, y)) and 1 or 0 for x in range(left, right)] for y in range(top, bottom)]
    return rows, left - origin_x, baseline - bottom, advance


def scale_rows(rows: list[list[int]], s: int) -> list[list[int]]:
    return [[bit for bit in row for _ in range(s)] for row in rows for _ in range(s)]


def pack(rows: list[list[int]]) -> list[int]:
    bits = [bit for row in rows for bit in row]
    bits += [0] * (-len(bits) % 8)
    return [int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8)]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("font", type=Path)
    ap.add_argument("--grid", type=int, default=8, help="the font's design pixel size")
    ap.add_argument("--scale", type=int, default=2)
    ap.add_argument("--name", default="font_pixel_16")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--preview", type=Path)
    args = ap.parse_args()

    font = ImageFont.truetype(str(args.font), args.grid)
    s = args.scale
    ascent, descent = font.getmetrics()

    bitmap: list[int] = []
    glyphs = []  # (codepoint, bitmap_index, adv_w, box_w, box_h, ofs_x, ofs_y)
    for ch in CHARS:
        if font.getmask(ch).getbbox() is None and ch != " " and ch != " ":
            continue  # not in the font
        rows, ofs_x, ofs_y, advance = rasterise(font, ch, args.grid)
        rows = scale_rows(rows, s)
        index = len(bitmap)
        bitmap += pack(rows)
        glyphs.append((ord(ch), index, advance * s * 16, len(rows[0]) if rows else 0, len(rows), ofs_x * s, ofs_y * s))

    # One cmap per run of consecutive code points.
    cmaps, start = [], 0
    for i in range(1, len(glyphs) + 1):
        if i == len(glyphs) or glyphs[i][0] != glyphs[i - 1][0] + 1:
            cmaps.append((glyphs[start][0], i - start, start + 1))
            start = i

    out = [f"/* {args.name}: {args.font.name} at {args.grid} px x{s}, 1 bpp. Generated by server/tools/pixel_font.py. */",
           '#include "lvgl.h"', "",
           "static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {"]
    for i in range(0, len(bitmap), 16):
        out.append("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i + 16]) + ",")
    out += ["};", "", "static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {",
            "    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},"]
    for cp, index, adv, w, h, ox, oy in glyphs:
        out.append(f"    {{.bitmap_index = {index}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, "
                   f".ofs_x = {ox}, .ofs_y = {oy}}}, /* U+{cp:04X} */")
    out += ["};", "", "static const lv_font_fmt_txt_cmap_t cmaps[] = {"]
    for range_start, length, glyph_start in cmaps:
        out.append(f"    {{.range_start = {range_start}, .range_length = {length}, .glyph_id_start = {glyph_start}, "
                   ".unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, "
                   ".type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},")
    out += ["};", "",
            "static const lv_font_fmt_txt_dsc_t font_dsc = {",
            "    .glyph_bitmap = glyph_bitmap,", "    .glyph_dsc = glyph_dsc,", "    .cmaps = cmaps,",
            "    .kern_dsc = NULL,", "    .kern_scale = 0,", f"    .cmap_num = {len(cmaps)},", "    .bpp = 1,",
            "    .kern_classes = 0,", "    .bitmap_format = 0,", "};", "",
            f"const lv_font_t {args.name} = {{",
            "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,",
            "    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
            f"    .line_height = {(ascent + descent) * s},",
            f"    .base_line = {descent * s},",
            "    .subpx = LV_FONT_SUBPX_NONE,",
            "    .underline_position = 0,", "    .underline_thickness = 0,",
            "    .dsc = &font_dsc,", "};", ""]
    args.out.write_text("\n".join(out))
    print(f"{args.out}: {len(glyphs)} glyphs, {len(bitmap)} bytes, line height {(ascent + descent) * s}")

    if args.preview:  # the glyphs as the C file encodes them, to eyeball the conversion
        text = "¿Qué ves? ¡Hola! Señal: -55 dBm · Batería 80 % … Cambiar wifi"
        line = (ascent + descent) * s
        img = Image.new("1", (len(text) * args.grid * s + 8, line + 8), 0)
        by_cp = {g[0]: g for g in glyphs}
        x = 4
        for ch in text:
            cp, index, adv, w, h, ox, oy = by_cp[ord(ch)]
            bits = [(bitmap[index + i // 8] >> (7 - i % 8)) & 1 for i in range(w * h)]
            for i, bit in enumerate(bits):
                if bit:
                    img.putpixel((x + ox + i % w, 4 + line - descent * s - oy - h + i // w), 1)
            x += adv // 16
        img.resize((img.width * 2, img.height * 2), Image.NEAREST).save(args.preview)


if __name__ == "__main__":
    main()
